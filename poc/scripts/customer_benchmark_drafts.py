def build_drafts():
    records = []
    for domain, name, title, body, claims in DRAFTS:
        text = title + "\n\n" + body + "\n"
        # Unknown values are explicitly unknown; authoring does not settle policy.
        context = [{"name": key, "value": value, "origin": "synthetic_assumption"} for key, value in (
            ("scope_complete", True), ("release_authorized", None), ("current_revision", True),
            ("core_asset", None), ("reader_scope", None), ("management_controls", None),
            ("impact_description", None), ("other_risk_present", None))]
        doc_id = "doc-" + value_digest({"text": text, "context": context})[:24]
        model_input = {"doc_id": doc_id, "text": text, "context": context}
        evidence = []
        for key, claim, quote in claims:
            if text.count(quote) != 1:
                raise ValueError("draft evidence quote ambiguous")
            start = text.index(quote)
            evidence.append({"name": key, "claim": claim, "quote": quote, "start": start,
                             "end": start + len(quote), "sha256": text_digest(quote), "status": "authored_binding_only"})
        records.append({**FLAGS, "schema_version": "customer-synthetic-draft-v1", "document_origin": "synthetic",
            "input": model_input, "input_sha256": value_digest(model_input), "family_id": "family-" + name,
            "scenario_id": "scenario-" + name, "template_family_id": "template-" + name, "domain": domain, "claims": evidence})
    return records
