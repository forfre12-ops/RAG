# 판정면·보정면은 요소마다 **고정 개수**다. 프레임을 추가해도 이 목록은 그대로여야
# 회차 간 비교가 성립한다(4차에서 비율 분할이 판정면을 흔든 것을 확인하고 바꿨다).
# 2차 판정면 전용 프레임. 목록 **끝에서부터** 떼므로 새 프레임을 끝에 붙이면
# 학습·보정·1차 판정면은 그대로이고 2차 판정면만 새로 생긴다.
# 1차 판정면과 문장이 겹치면 2차가 새 증거가 되지 못한다(실측: 겹침 108/109 였다).
HOLDOUT2_FRAMES = {"secrecy": 4, "value": 6, "management": 4}
HOLDOUT_FRAMES = {"secrecy": 4, "value": 6, "management": 4}
CALIB_FRAMES = {"secrecy": 2, "value": 4, "management": 2}

# 보정면이 따로 필요한 이유(실측). 게이트는 min(head_conf) >= tau 로 동작하는데 4차 모델은
# tau 0.995 에서 자동 73건인 것이 0.999 에서 0건이 된다 — 신뢰도가 뭉쳐 있어 임계가
# 사실상 스위치처럼 동작한다. 온도 보정이 그 분포를 펴 준다.
#   dev 는 못 쓴다: 프레임을 다 봐서 MAE 0.000 이라 온도 추정 신호가 없다(v6 가 val
#                  정확도 1.000 때문에 온도 0.05 로 퇴화한 것과 같은 함정).
#   판정면도 못 쓴다: 거기서 맞추면 판정면이 튜닝면이 되어 잠금이 풀린다.


def frames_for(factor: str, split: str = "all") -> list[dict]:
    """프레임 목록. **문장이 아니라 프레임 단위로** 자른다.

    문장 단위로 자르면 같은 어휘의 긍정형과 부정형이 서로 다른 분할에 들어가고,
    학습셋 안에서 그 어휘가 한 상태와만 붙어 어휘 연상이 최적해가 된다. 1차 판정이
    정확히 그 결함으로 실패했다.
    """
    fr = FRAMES[factor]
    # 판정면과 보정면을 **개수로 고정**한다. 비율로 자르면 학습 프레임을 추가할 때마다
    # 경계가 밀려 판정면 구성이 바뀌고, 회차 간 비교가 성립하지 않는다. 실제로 4차 뒤
    # 학습 프레임 6종을 넣자 판정면에 새 프레임이 끼어들어 평균이 흔들렸다.
    # 목록 **끝에서부터** 판정 -> 보정 순으로 떼므로, 새 프레임은 항상 학습에만 들어간다.
    n_h2 = HOLDOUT2_FRAMES.get(factor, 0)
    n_hold = HOLDOUT_FRAMES.get(factor, 6)
    n_cal = CALIB_FRAMES.get(factor, 4)
    h2_start = len(fr) - n_h2
    hold_start = h2_start - n_hold
    cal_start = hold_start - n_cal
    if cal_start < 1:
        raise ValueError(f"{factor}: 프레임이 부족하다 - 학습 몫이 남지 않는다")
    if split == "train":
        return list(fr[:cal_start])
    if split == "calib":
        return list(fr[cal_start:hold_start])
    if split == "holdout":
        return list(fr[hold_start:h2_start])
    if split == "holdout2":
        return list(fr[h2_start:])
    return list(fr)


def sentences_for(factor: str, state: str, level: int | None, split: str = "all") -> list[str]:
    key = "absent" if state == "proven_absent" else level
    if state == "unknown":
        return []
    return [f[key] for f in frames_for(factor, split)]


def near_miss_for(factor: str, split: str = "all") -> list[tuple[str, str]]:
    return [f["trap"] for f in frames_for(factor, split)]


def split_overlap() -> list[str]:
    """학습·홀드아웃 문장 교집합. 0 이어야 한다."""
    seen: dict[str, set] = {"train": set(), "calib": set(), "holdout": set(),
                            "holdout2": set()}
    for factor in FACTORS:
        for sp in seen:
            for st, lv in (("proven_absent", None), ("present", 1), ("present", 2)):
                seen[sp] |= set(sentences_for(factor, st, lv, sp))
            seen[sp] |= {s for s, _ in near_miss_for(factor, sp)}
    keys = list(seen)
    bad: set = set()
    for i, a in enumerate(keys):
        for b in keys[i + 1:]:
            bad |= seen[a] & seen[b]
    return sorted(bad)


def audit() -> list[str]:
    """프레임 계약을 검사한다 — 생성 전에 부른다."""
    problems: list[str] = []
    GRADE_WORDS = ("TS", "S1", "S2", "S3", "영업비밀에 해당", "등급", "분류된다")
    for factor, frames in FRAMES.items():
        ids = [f["id"] for f in frames]
        if len(ids) != len(set(ids)):
            problems.append(f"[{factor}] 프레임 id 중복")
        for f in frames:
            for key in ("absent", 1, 2):
                if key not in f or not f[key]:
                    problems.append(f"[{factor}/{f['id']}] {key} 누락")
                    continue
                if any(w in f[key] for w in GRADE_WORDS):
                    problems.append(f"[{factor}/{f['id']}/{key}] 등급 결론 문장")
            if "trap" not in f:
                problems.append(f"[{factor}/{f['id']}] trap 누락")
        # 프레임 수가 적으면 분할 후 한쪽이 비거나 얇아진다
        if len(frames) < 10:
            problems.append(f"[{factor}] 프레임 {len(frames)}개 — 최소 10개 필요")
    if split_overlap():
        problems.append(f"학습·홀드아웃 문장 교집합 {len(split_overlap())}종")
    return problems


def frame_lexical_balance() -> dict[str, float]:
    """1차 실패의 직접 지표 — 학습셋 안에서 어휘가 한 상태에 쏠렸는가.

    프레임 구조가 제대로면 같은 프레임의 세 상태가 모두 학습셋에 있으므로 쏠림이 없다.
    값은 '학습 lv2 어휘 중 학습 absent 와도 겹치는 비율' 이고, 높을수록 어휘만으로는
    상태를 못 가른다는 뜻이라 **높아야 좋다**(1차 실패 시 이 값이 낮았다).
    """
    import re

    def toks(ss):
        return {w for s in ss for w in re.findall(r"[가-힣]{2,}", s)}

    out = {}
    for factor in FACTORS:
        a = toks(sentences_for(factor, "proven_absent", None, "train"))
        b = toks(sentences_for(factor, "present", 2, "train"))
        out[factor] = round(len(a & b) / len(b), 3) if b else 0.0
    return out


