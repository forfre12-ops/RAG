    print(f"\n학습·홀드 문장 교집합 {len(split_overlap())}종")
    print(f"감사 {'문제 없음' if not probs else str(len(probs)) + '건'}")
    for p in probs:
        print(f"  - {p}")
    print("\n학습셋 내 어휘 균형 (lv2 어휘 중 absent 와 겹치는 비율 — 높아야 좋다)")
    for k, v in frame_lexical_balance().items():
        print(f"  {k:11s} {v:.3f}")
