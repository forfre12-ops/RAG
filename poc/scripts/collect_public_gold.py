def _sha1(text: str) -> str:
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:16]


# ---------------------------------------------------------------------------
# S3 — oss_corpus 판례 문서 (이미 공개 → 정의상 S3)
# ---------------------------------------------------------------------------

def collect_s3_from_oss(n: int, seed: int) -> list[dict]:
    """oss_corpus에서 판례 문서를 S3로 수집.

    법원 공개 판결문은 '이미 공개된 문서'이므로 정의상 S3.
    rule labeler가 내용 키워드를 보고 TS/S1로 잘못 라벨한 경우에도 S3가 맞음.
    """
    files = sorted(OSS_CORPUS.glob("*.json"))
    rng = random.Random(seed)
    rng.shuffle(files)

    records = []
    for f in files:
        d = json.loads(f.read_text(encoding="utf-8"))
        if d.get("source", "") not in ("판례", "판례(1000+)", "판례(2000+)", "판례(3000+)"):
            continue
        body = d.get("body", "")
        if not body or len(body) < 500:
            continue
        title = d.get("title", "")
        text = f"{title}\n\n{body[:3000]}"
        records.append({
            "doc_id": _sha1(text),
            "text": text,
            "label": "S3",
            "label_source": "public_definitive",
            "review_status": "accepted",
            "reviewer_id": "public_gold_collector",
            "source": "판례_공개문서",
            "domain": d.get("domain", "법률"),
            "legal_reference": "공개 법원 판결문 — 이미 공개된 문서는 정의상 S3 (비밀성 요건 미충족)",
            "evidence_spans": [{"start": 0, "end": 50, "factor": "NON_PUBLICITY",
                                 "reason": "법원 공개 판결문 — 일반에 공개된 정보"}],
            "notes": f"oss_corpus/{f.name} — 공개 판례",
        })
        if len(records) >= n:
            break

    return records


