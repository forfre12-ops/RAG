def build_scenario_records(scenarios: list[dict], label: str, label_source: str) -> list[dict]:
    records = []
    for s in scenarios:
        text = f"{s['title']}\n\n{s['body']}"
        records.append({
            "doc_id": _sha1(text),
            "text": text,
            "label": label,
            "label_source": label_source,
            "review_status": "accepted",
            "reviewer_id": "public_gold_collector",
            "source": "public_scenario",
            "domain": "mixed",
            "legal_reference": s.get("legal_reference", ""),
            "evidence_spans": [
                {"start": 0, "end": min(100, len(text)), "factor": "NON_PUBLICITY",
                 "reason": f"{label} — 공개 법령/판례 기반 분류 근거 있음"}
            ],
            "notes": "공개 출처 기반 시나리오 — 법적 근거 명시",
        })
    return records


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--n-s3", type=int, default=45, help="S3 oss_corpus 샘플 수")
    ap.add_argument("--n-s2", type=int, default=20, help="S2 시나리오 수 (최대 20)")
    ap.add_argument("--n-s1", type=int, default=20, help="S1 시나리오 수 (최대 20)")
    ap.add_argument("--n-ts", type=int, default=15, help="TS 시나리오 수 (최대 15)")
    ap.add_argument("--seed", type=int, default=99)
    ap.add_argument("--out", default=str(GOLD_REAL))
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args()

    records: list[dict] = []

    # S3 — oss_corpus 공개 판례
    if OSS_CORPUS.exists():
        s3 = collect_s3_from_oss(args.n_s3, args.seed)
        records.extend(s3)
        print(f"S3 (public 판례): {len(s3)}건")
    else:
        print("[SKIP] oss_corpus 없음")

    # S2 — KOIPA 가이드라인 기반
    s2_pool = _S2_SCENARIOS + _S2_EXTRA + _S2_ADD + _S2_ADD2
    s2_recs = build_scenario_records(s2_pool[:args.n_s2], "S2", "koipa_case_based")
    records.extend(s2_recs)
    print(f"S2 (KOIPA 사례): {len(s2_recs)}건")

    # S1 — 대법원 판결 기반
    s1_pool = _S1_SCENARIOS + _S1_EXTRA + _S1_ADD + _S1_ADD2
    s1_recs = build_scenario_records(s1_pool[:args.n_s1], "S1", "koipa_case_based")
    records.extend(s1_recs)
    print(f"S1 (영업비밀 판결): {len(s1_recs)}건")

    # TS — 국가핵심기술 지정 근거
    ts_pool = _TS_SCENARIOS + _TS_ADD + _TS_ADD2
    ts_recs = build_scenario_records(ts_pool[:args.n_ts], "TS", "nkt_designated")
    records.extend(ts_recs)
    print(f"TS (국가핵심기술): {len(ts_recs)}건")

    total = len(records)
    from collections import Counter
    dist = dict(Counter(r["label"] for r in records))
    print(f"\n총 {total}건 | 분포: {dist}")

    if args.dry_run:
        print("\n[DRY-RUN] 실제 파일 수정 없음")
        return 0

    # 기존 gold_real과 중복 제거
    out = Path(args.out)
    existing_ids: set[str] = set()
    if out.exists():
        for line in out.read_text(encoding="utf-8").splitlines():
            if line.strip() and not line.startswith("#"):
                existing_ids.add(json.loads(line).get("doc_id", ""))

    new_records = [r for r in records if r["doc_id"] not in existing_ids]
    skipped = total - len(new_records)

    if new_records:
        with out.open("a", encoding="utf-8") as f:
            for r in new_records:
                f.write(json.dumps(r, ensure_ascii=False) + "\n")
        print(f"\n[OK] {len(new_records)}건 추가 → {out}")
        if skipped:
            print(f"[SKIP] {skipped}건 중복")
    else:
        print("[INFO] 추가할 새 레코드 없음 (전부 중복)")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
