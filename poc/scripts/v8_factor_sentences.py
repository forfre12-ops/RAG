POOLS = {"secrecy": SECRECY, "value": VALUE, "management": MANAGEMENT}


# 학습과 홀드아웃은 **문장을 공유하지 않는다.**
#
# 형태만 홀드아웃하면 "미관측 형태"는 검증되지만 "미관측 표현"은 검증되지 않는다. v6 사전등록
# 문서가 바로 이 분리(eval_fact_pools ↔ v6_fact_pools, 문장 공유 0종)로 두 가설을 갈랐다:
#
#   (A) 문자열 -> 수준 매핑을 외웠다   실문서에서 무너진다
#   (B) 사실 -> 수준 을 일반화했다     다르게 쓰여도 읽는다
#
# 학습 손실만으로는 A 와 B 를 구분할 수 없다. 표현이 분리된 홀드아웃만이 분리 검정이 된다.
SPLIT_RATIO = 0.6   # 앞 60% 학습 · 뒤 40% 홀드아웃


def _slice(items: list, split: str) -> list:
    cut = max(1, round(len(items) * SPLIT_RATIO))
    if split == "train":
        return list(items[:cut])
    if split == "holdout":
        return list(items[cut:])
    return list(items)   # "all" — 감사·통계용


def sentences_for(factor: str, state: str, level: int | None, split: str = "all") -> list[str]:
    """(요소, 상태, 수준) 에 해당하는 문장 풀. split 으로 학습·홀드아웃을 갈라 준다."""
    pool = POOLS[factor]
    if state == "proven_absent":
        return _slice(pool["proven_absent"], split)
    if state == "present":
        return _slice(pool[level], split)
    return []  # unknown 은 문장을 넣지 않는다 — 그게 unknown 의 정의다


def near_miss_for(factor: str, split: str = "all") -> list[tuple[str, str]]:
    """proven_absent 로 오독되기 쉬운 함정 문장과 그 유형."""
    return _slice(POOLS[factor]["near_miss"], split)


def split_overlap() -> list[str]:
    """학습·홀드아웃 문장 교집합. 0 이어야 한다 — 아니면 판정면이 오염된다."""
    tr, ho = set(), set()
    for factor in POOLS:
        for state, lv in (("proven_absent", None), ("present", 1), ("present", 2)):
            tr |= set(sentences_for(factor, state, lv, "train"))
            ho |= set(sentences_for(factor, state, lv, "holdout"))
        tr |= {s for s, _ in near_miss_for(factor, "train")}
        ho |= {s for s, _ in near_miss_for(factor, "holdout")}
    return sorted(tr & ho)


def audit() -> list[str]:
    """풀 자체의 결함을 잡는다 — 생성 전에 부른다."""
    problems: list[str] = []
    GRADE_WORDS = ("TS", "S1", "S2", "S3", "영업비밀에 해당", "등급", "분류된다")
    seen: dict[str, tuple[str, object]] = {}
    for factor, pool in POOLS.items():
        for key in ("proven_absent", 1, 2):
            for s in pool[key]:
                if any(w in s for w in GRADE_WORDS):
                    problems.append(f"[{factor}/{key}] 등급 결론 문장: {s}")
                if s in seen:
                    problems.append(f"[{factor}/{key}] 중복 문장(다른 수준과 공유): {s}")
                seen[s] = (factor, key)
        for s, kind in pool["near_miss"]:
            if s in seen:
                problems.append(f"[{factor}/near_miss] 정상 풀과 겹침: {s}")
        # 수준마다 최소 4종 — 변형이 적으면 모델이 문자열을 외운다
        for key in ("proven_absent", 1, 2):
            if len(pool[key]) < 4:
                problems.append(f"[{factor}/{key}] 변형 {len(pool[key])}종 — 최소 4종 필요")
    return problems


