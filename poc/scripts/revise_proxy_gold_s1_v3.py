    REV.mkdir(exist_ok=True)
    prepared=[]
    for doc_id,(kind,focus,data,trigger,owners) in CASES.items():
        meta_path=DIR/f"{doc_id}.metadata.json"; meta=json.loads(meta_path.read_text(encoding="utf-8"))
        if meta.get("content_revision_path"): raise FileExistsError(f"revision already set: {doc_id}")
        source=list(DIR.glob(f"{doc_id}_*.md"))
        if len(source)!=1: raise ValueError(doc_id)
        appendix=_commercial(focus,data,trigger,owners) if kind=="commercial" else _operations(focus,data,trigger,owners)
        text=(source[0].read_text(encoding="utf-8").rstrip()+appendix).strip()+"\n"
        path=REV/f"{doc_id}.v3.md"
        if path.exists() or len(text)<4000: raise ValueError(f"invalid revision {doc_id}: {len(text)}")
        prepared.append((doc_id,meta_path,meta,path,text))
    for doc_id,meta_path,meta,path,text in prepared:
        path.write_text(text,encoding="utf-8"); meta["content_revision"]="v3"; meta["content_revision_path"]=str(path.relative_to(DIR)).replace("\\","/"); meta["content_revision_note"]="S1 decision context and operational/negotiation evidence expansion"; meta_path.write_text(json.dumps(meta,ensure_ascii=False,indent=2)+"\n",encoding="utf-8"); print(f"{doc_id}\t{len(text)}")
    return 0

