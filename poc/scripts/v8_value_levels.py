# 목록 끝에서 개수를 고정해 가른다. 새 문장은 앞에 붙으므로 판정·보정면이 안 변한다.
CALIB_N, HOLD1_N, HOLD2_N = 1, 1, 2


def content_for(domain: str, level: int, split: str) -> list[str]:
    """도메인·수준·면에 해당하는 내용 문장."""
    pool = VALUE_CONTENT[domain][level]
    h2 = pool[len(pool) - HOLD2_N:]
    h1 = pool[len(pool) - HOLD2_N - HOLD1_N:len(pool) - HOLD2_N]
    cal = pool[len(pool) - HOLD2_N - HOLD1_N - CALIB_N:len(pool) - HOLD2_N - HOLD1_N]
    tr = pool[:len(pool) - HOLD2_N - HOLD1_N - CALIB_N]
    return {"train": tr, "calib": cal, "holdout": h1, "holdout2": h2}[split]


DOMAINS = tuple(VALUE_CONTENT)


def audit() -> list[str]:
    """수준이 주제로 새지 않는지 확인한다."""
    bad: list[str] = []
    for d, lv in VALUE_CONTENT.items():
        if set(lv) != {1, 2}:
            bad.append(f"{d}: 두 수준을 모두 갖지 않는다")
        if len(lv[1]) != len(lv[2]):
            bad.append(f"{d}: 수준별 문장 수가 다르다 {len(lv[1])} vs {len(lv[2])}")
    # 같은 문장이 두 수준에 들어가면 안 된다
    seen: dict[str, tuple[str, int]] = {}
    for d, lv in VALUE_CONTENT.items():
        for l, ss in lv.items():
            for s in ss:
                if s in seen:
                    bad.append(f"중복 «{s[:30]}» {seen[s]} 와 {(d, l)}")
                seen[s] = (d, l)
    return bad


