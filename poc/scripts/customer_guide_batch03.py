def build_new_cases(specs=None):
    specs = CASES if specs is None else specs
    require(bool(specs) and len({r["key"] for r in specs}) == len(specs), "batch03_source_keys_invalid")
    out = []
    for row in specs:
        quotes = re.findall(r"«([^«»]+)»", row["marked"])
        require(len(quotes) == 2, "batch03_two_quotes_required")
        text = row["title"] + "\n\n" + row["marked"].replace("«", "").replace("»", "") + "\n"
        inp = {"doc_id": "doc-" + value_digest({"text": text, "context": []})[:24], "text": text, "context": []}
        claims = []
        for i, quote in enumerate(quotes, 1):
            require(text.count(quote) == 1, "batch03_quote_ambiguous")
            start = text.index(quote)
            claims.append({"name": f"statement-{i}", "claim": quote, "quote": quote, "start": start,
                           "end": start+len(quote), "sha256": text_digest(quote), "status": "authored_binding_only"})
        draft = {**FLAGS, "schema_version": "customer-synthetic-draft-v1", "document_origin": "synthetic",
                 "input": inp, "input_sha256": value_digest(inp), "family_id": "family-"+row["key"],
                 "scenario_id": "scenario-"+row["key"], "template_family_id": "template-"+row["key"],
                 "domain": row["domain"], "claims": claims}
        access, cost, hours, readers, release = row["setting"]
        access_note = {"custodian": "이 판본은 공개되지 않았고 보유자를 통하지 않고는 취득할 수 없다.",
                       "difficult": "판본은 일반 공개되지 않았으나 계약·자격 확인을 거친 제3자 경로로도 취득할 수 있다.",
                       "public": "이 판본 전체가 신청 없이 읽을 수 있게 공개되었으며 숨겨진 부록은 없다."}[access]
        reader_note = {"named": "개별 승인 계정만 읽도록 제한이 실제 적용되어 있다.",
                       "need": "업무 필요 역할만 읽는 제한이 실제 적용되며 개인별 추가 승인은 없다.",
                       "staff": "모든 직원이 알아야 하며 사내 직무·개인 제한은 없고 외부 배포 허가는 없다.",
                       "open": "비밀 유지 대상이 아니며 내외부 누구나 읽을 수 있다."}[readers]
        rationale = (f"가상 조건: {access_note} 해당 정보의 직접 투입은 {cost}원, {hours}인시로 설정했다. "
                     + row["investment"] + " " + reader_note + " 현실의 사실이나 고객사 등급을 인증하는 답이 아니다.")
        triple = build_case(draft, premises((access, cost, hours, readers, release, rationale)), rationale)
        require(triple[1] is not None, "batch03_unresolved_premises")
        out.append(triple)
    return out
