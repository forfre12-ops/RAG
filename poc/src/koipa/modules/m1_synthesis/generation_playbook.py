def playbook_text() -> str:
    """생성 프롬프트 [구조·완성도 요구] 칸에 덧붙일 지침 블록.

    9/26 A/B 시험에 쓴 문자열과 같은 모양(번호 붙은 규칙 + 반복 금지 낱말 한 줄)이다.
    """
    lines = [
        "[작성 지침 — 앞선 생성 시행에서 얻은 규칙. 아래를 반드시 지킨다]",
    ]
    lines.extend(
        f"{i}. {rule}" for i, rule in enumerate(GENERATION_RULES, start=1)
    )
    avoid = ", ".join(f"'{w}'" for w in AVOID_PHRASES)
    lines.append(
        f"{len(GENERATION_RULES) + 1}. 아래 표현은 이전 문서에서 너무 반복돼 쓰지 않는다: "
        f"{avoid}."
    )
    return "\n".join(lines)


def playbook_version() -> str:
    """규칙 내용 해시 — generator.body_prompt_version() 과 같은 방식(내용이 바뀌면 값도 바뀐다)."""
    digest = hashlib.sha256(playbook_text().encode("utf-8"))
    return "pb1-" + digest.hexdigest()[:8]
