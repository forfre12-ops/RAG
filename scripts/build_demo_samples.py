def main() -> int:
    print("KOIPA AI 데모 콘솔 — 샘플·법령 빌드 v2 (실 사내 문서 골격)")
    print("=" * 60)

    print("\n[1/3] 12 샘플 본문 빌드")
    samples = build_all_samples()
    for s in samples:
        print(f"  {s['id']:25s} {s['char_count']:5d}자  {s['title']}")
    total = sum(s["char_count"] for s in samples)
    print(f"\n  총 {len(samples)}건, {total:,}자, 평균 {total // len(samples):,}자")

    print("\n[2/3] ClassifyService 의도 등급 검증")
    skip_validate = os.getenv("DEMO_SAMPLES_SKIP_VALIDATE", "").lower() in (
        "1", "true", "yes",
    )
    failures: list[str] = []
    if skip_validate:
        print("  (DEMO_SAMPLES_SKIP_VALIDATE=1 — 검증 생략)")
    else:
        failures = validate_samples(samples, strict=False)

    print("\n[3/3] samples.js export")
    export_samples_js(samples, LEGAL_REFERENCES, SAMPLES_JS)

    if failures:
        print(
            f"\n⚠ 검증 실패 {len(failures)}건 — 실제 환경에서 등급이 달라질 수 있음.",
        )
        if os.getenv("DEMO_SAMPLES_STRICT", "").lower() in ("1", "true", "yes"):
            return 1
    print("\n✓ 완료")
    return 0


if __name__ == "__main__":
    sys.exit(main())
