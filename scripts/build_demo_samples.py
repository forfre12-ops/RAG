def build_all_samples() -> list[dict]:
    out: list[dict] = []
    for sid, meta in DOMAINS.items():
        grade = meta["grade"]
        label_short, label_full = GRADE_LABEL[grade]
        out.append({
            "id": sid,
            "grade": grade,
            "grade_label": label_full,
            "domain": meta["domain"],
            "title": TITLES[sid],
            "body": BODIES[sid].strip(),
            "toggle_keywords": list(meta["toggle_keywords"]),
            "char_count": len(BODIES[sid].strip()),
        })
    return out


