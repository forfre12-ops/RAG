def validate_samples(samples: list[dict], strict: bool = True) -> list[str]:
    failures: list[str] = []
    try:
        from lloydk.schemas.classify import ClassifyRequest  # noqa: PLC0415
        from lloydk.services.classify_service import ClassifyService  # noqa: PLC0415
    except Exception as exc:  # noqa: BLE001
        print(f"  ⚠ ClassifyService import 실패 — 검증 건너뜀: {exc}", file=sys.stderr)
        return failures

    svc = ClassifyService.get_instance()
    for s in samples:
        req = ClassifyRequest(
            doc_id=s["id"],
            content=s["body"],
            title=s["title"],
            use_rag=False,
            return_evidence=True,
        )
        try:
            res = svc.classify(req)
            actual = res.label.value if hasattr(res.label, "value") else str(res.label)
            if actual != s["grade"]:
                msg = (
                    f"  ✗ {s['id']:25s} {s['char_count']:5d}자 — 기대 {s['grade']} 실제 {actual} "
                    f"(conf={res.confidence:.2f})"
                )
                failures.append(msg)
                print(msg, file=sys.stderr)
            else:
                print(
                    f"  ✓ {s['id']:25s} {s['char_count']:5d}자 — {actual} "
                    f"(conf={res.confidence:.2f}, evidence={len(res.evidence)})"
                )
        except Exception as exc:  # noqa: BLE001
            msg = f"  ✗ {s['id']} — 분류 호출 실패: {exc}"
            failures.append(msg)
            print(msg, file=sys.stderr)

    if failures and strict:
        print(
            f"\n총 {len(failures)}건 실패 — 본문/키워드 조정 후 재빌드 필요.",
            file=sys.stderr,
        )
    return failures


