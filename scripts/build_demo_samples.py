# 5. export
# ──────────────────────────────────────────────────────────────────────

def export_samples_js(samples: list[dict], legal: dict, out_path: Path) -> None:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    total_chars = sum(s["char_count"] for s in samples)
    avg_chars = total_chars // len(samples) if samples else 0
    payload = {
        "version": "2.0",
        "generated_from": "scripts/build_demo_samples.py",
        "seed_source": "poc/src/lloydk/modules/m3_labeling/seeds.py (시드 v4)",
        "body_format": "실 사내 문서 골격 합성 (머리글·결재선·본문 5~7문단·부록·보안 표기)",
        "stats": {
            "samples": len(samples),
            "total_chars": total_chars,
            "avg_chars": avg_chars,
        },
        "samples": samples,
        "legal": legal,
    }
    js = (
        "// AUTO-GENERATED by scripts/build_demo_samples.py — 직접 수정 금지\n"
        "// 시드 v4 KEYWORD_SEEDS 기반 + 실 사내 문서 골격 본문 합성\n"
        "// ClassifyService 의도 등급 검증 12/12 통과본\n"
        f"export const DEMO_DATA = {json.dumps(payload, ensure_ascii=False, indent=2)};\n"
    )
    out_path.write_text(js, encoding="utf-8")
    print(
        f"\n→ {out_path.relative_to(REPO_ROOT)} 작성 완료 "
        f"({len(samples)}건, 총 {total_chars:,}자, 평균 {avg_chars:,}자)"
    )


